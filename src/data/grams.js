const OZ = 29.57
/** กรัมของ "ทั้งหน่วยตั้งต้น" ตามที่เขียนในหน่วย เช่น '1 ถ้วย 150 g' · '2 ช้อนโต๊ะ (30 g)' · '1 กระป๋อง 325 มล.' · '1 แก้ว (16 oz)' — ไม่มี = null */
const explicit = (u) => {
  const rest = u.replace(/^\S+\s*/, '')
  const m = rest.match(/(\d+(?:\.\d+)?)\s*(?:g|มล\.)/)
  if (m) return Number(m[1])
  const o = rest.match(/(\d+(?:\.\d+)?)\s*oz/)
  return o ? Math.round(Number(o[1]) * OZ) : null
}

/** กรัมของ "ทั้งหน่วยตั้งต้น" (เช่น 1 ชาม / 4 ชิ้น) — null ถ้าประเมินไม่ได้ (ให้ใช้ "กรอกเอง ต่อ 100 g") */
export function gramsPerUnit(food) {
  const u = unitInfo(food)
  if (u.kind === 'g') return u.base // หน่วยเป็นกรัมอยู่แล้ว
  return NAME[food.n] ?? explicit(food.u) ?? CATWORD[`${food.cat}:${u.word}`] ?? null
}

