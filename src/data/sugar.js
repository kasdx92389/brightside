/** น้ำตาลของรายการที่บันทึก: ใช้ค่าที่บันทึกไว้ (su) ถ้าไม่มี (รายการเก่าก่อนมีน้ำตาล) ประมาณจากฐานข้อมูลตามปริมาณ */
export function itemSugar(it, byId) {
  if (it.su != null) return it.su
  const food = byId?.[it.id]
  return food ? r1(sugarOf(food) * (it.q || 1)) : 0
}

