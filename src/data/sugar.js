/** น้ำตาลทั้งหมด (g) ต่อ 1 หน่วยตั้งต้นของอาหาร — ไม่น้อยกว่าน้ำตาลเติม ไม่เกินคาร์บ */
export function sugarTotalOf(food) {
  if (food.sg != null) return food.sg
  if (food.id?.startsWith('my-')) return sugarOf(food) // เมนูของฉันรุ่นก่อนมีช่องน้ำตาลรวม: ใช้เท่าที่รู้ (น้ำตาลเติม)
  let v = TOTAL_NAME[food.n]
  if (v == null) {
    let fr = TOTAL_RULES.find(([re]) => re.test(food.n))?.[1]
    if (fr == null && food.cat === 'plant') fr = PLANT_RULES.find(([re]) => re.test(food.n))?.[1]
    v = (fr ?? TOTAL_CAT[food.cat] ?? 0.3) * food.c
  }
  return r1(Math.min(Math.max(v, sugarOf(food)), Math.max(food.c, 0)))
}

