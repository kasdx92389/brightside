/** น้ำตาลเติม (g) ต่อ 1 หน่วยตั้งต้นของอาหาร */
export function sugarOf(food) {
  if (food.su != null) return food.su // เมนูของฉัน / สูตร / ค่าจากฉลาก
  if (food.id?.startsWith('my-')) return 0 // เมนูของฉันรุ่นก่อนมีช่องน้ำตาล: ไม่รู้ = 0 (ไม่เดาจากชื่อ)
  if (NAME[food.n] != null) return NAME[food.n]
  for (const [re, fr] of RULES) if (re.test(food.n)) return r1(fr * food.c)
  return 0
}

