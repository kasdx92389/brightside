/** โซเดียม (มก.) ต่อ 1 หน่วยตั้งต้นของอาหาร */
export function sodiumOf(food) {
  if (food.na != null) return food.na // เมนูของฉัน / ค่าจากฉลาก
  if (NAME[food.n] != null) return NAME[food.n]
  for (const [re, r] of RULES) if (re.test(food.n)) return Math.round((r.abs ?? r.d * food.k) / 10) * 10
  return Math.round(((CAT[food.cat] ?? 1) * food.k) / 10) * 10
}

