/** โซเดียมของรายการที่บันทึก: ใช้ค่าที่บันทึกไว้ (na) ถ้าไม่มี (รายการเก่าก่อนมีโซเดียม) ประมาณจากฐานข้อมูลตามปริมาณ */
export function itemSodium(it, byId) {
  if (it.na != null) return it.na
  const food = byId?.[it.id]
  return food ? Math.round(sodiumOf(food) * (it.q || 1)) : 0
}
